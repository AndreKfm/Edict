# Writes src/Edict.Engine/Common/Registry.cs, the console's names as the reference build registers them: every cvar
# with its default, archive and server flags, in the order of the cvar list (Cvar_RegisterVariable puts each new
# one in front), and every command Cmd_AddCommand registers.
# Inputs: the build's sources preprocessed with its flags (clang -E -P, so that the #ifdefs fall as they do in the
# build), and an .edh with an 'I' record (-edictclient), whose cvar list is the order and the set registered at run
# time. A cvar of the list without a definition in the sources, or a definition registered twice, stops the script.
# Usage: python3 -I tools/registry.py <dir of .i files> <file.edh> <out.cs>
import glob, os, re, struct, sys

pp, edh, out = sys.argv[1], sys.argv[2], sys.argv[3]
text = ''.join(open(f, encoding='latin-1').read() for f in sorted(glob.glob(os.path.join(pp, '*.i'))))

defs = {}
for m in re.finditer(r'\bcvar_t\s+(\w+)\s*=\s*\{\s*"([^"]*)"\s*,\s*"([^"]*)"\s*(?:,\s*(\w+)\s*)?(?:,\s*(\w+)\s*)?\}', text):
    name, default = m.group(2), m.group(3)
    flag = lambda g: g is not None and g not in ('false', '0')
    d = (default, flag(m.group(4)), flag(m.group(5)))
    if name in defs and defs[name] != d:
        raise SystemExit('two definitions of %s: %r, %r' % (name, defs[name], d))
    defs[name] = d
commands = []
for m in re.finditer(r'\bCmd_AddCommand\s*\(\s*"([^"]*)"', text):
    if m.group(1) not in commands:
        commands.append(m.group(1))

d = open(edh, 'rb').read()
p, order = 12, None
while p < len(d) and order is None:
    k = d[p:p + 1]; p += 1
    if k == b'M':
        p += 76
    elif k == b'V':
        p += 28
    elif k == b'I':
        p += 4
        n, = struct.unpack_from('<I', d, p); p += 4
        order = []
        for _ in range(n):
            e = d.index(b'\0', p); name = d[p:e].decode('latin-1'); p = d.index(b'\0', e + 1) + 1
            order.append(name)
    else:
        raise SystemExit('%s: no I record before %r' % (edh, k))
missing = [n for n in order if n not in defs]
if missing:
    raise SystemExit('registered but not defined: %s' % missing)


def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = ['// Copyright (C) 2026 Andre Kaufmann',
         '// SPDX-License-Identifier: GPL-2.0-or-later',
         '// Generated by tools/registry.py from the reference build; do not edit.',
         '',
         'namespace Edict.Engine;',
         '',
         '/// <summary>',
         '/// The console\'s names as the reference registers them in Host_Init: the cvars in the order of the cvar list',
         '/// (each registration puts the new one in front), with their defaults and flags, and the commands.',
         '/// </summary>',
         'public static class Registry',
         '{',
         '    /// <summary>A cvar_t as defined: name, default string, archive (written to config.cfg), server (changes are announced).</summary>',
         '    public readonly record struct CvarDef(string Name, string Default, bool Archive, bool Server);',
         '',
         '    /// <summary>The cvar list, from cvar_vars on.</summary>',
         '    public static readonly CvarDef[] Cvars =',
         '    [']
for n in order:
    default, archive, server = defs[n]
    lines.append('        new(%s, %s, %s, %s),' % (cs(n), cs(default), 'true' if archive else 'false', 'true' if server else 'false'))
lines += ['    ];', '',
          '    /// <summary>Every command Cmd_AddCommand registers in this build.</summary>',
          '    public static readonly string[] Commands =',
          '    [']
for i in range(0, len(commands), 6):
    lines.append('        ' + ', '.join(cs(c) for c in commands[i:i + 6]) + ',')
lines += ['    ];', '}', '']
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('%d cvars, %d commands' % (len(order), len(commands)))
