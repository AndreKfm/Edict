using Microsoft.CodeAnalysis;

namespace Edict.NoAlloc.Analyzers;

/// <summary>
/// Adds internal copies of [NoAlloc], [NoAllocUnchecked] and their enums to every compilation that uses the
/// analyzer, so the analyzer package is the only dependency. The copies are marked embedded: other assemblies never see them, so
/// InternalsVisibleTo cannot cause duplicate-type conflicts, while their use on members stays in metadata and is
/// recognized across assemblies by name. Set the MSBuild property EdictNoAllocInjectAttributes to false when
/// referencing the Edict.NoAlloc.Annotations project instead.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class AttributeInjector : IIncrementalGenerator
{
    internal const string OptionName = "build_property.EdictNoAllocInjectAttributes";
    internal const string HintName = "Edict.NoAlloc.Attributes.g.cs";

    internal const string Source = """
        // <auto-generated/>
        #nullable enable
        namespace Edict.NoAlloc
        {
            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.Flags]
            internal enum Constraints
            {
                None = 0, NoAlloc = 1, NoLock = 2, NoBlock = 4, NoAsync = 8, NoThrow = 16, NoDynamic = 32, NoInit = 64,
                All = NoAlloc | NoLock | NoBlock | NoAsync | NoThrow | NoDynamic | NoInit,
            }

            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.Flags]
            internal enum Allow
            {
                None = 0, Alloc = 1, Lock = 2, Block = 4, Async = 8, Throw = 16, Dynamic = 32, Init = 64, Spin = 128,
            }

            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.AttributeUsage(
                global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct | global::System.AttributeTargets.Interface
                | global::System.AttributeTargets.Method | global::System.AttributeTargets.Constructor | global::System.AttributeTargets.Property,
                Inherited = false, AllowMultiple = false)]
            internal sealed class NoAllocAttribute : global::System.Attribute
            {
                public NoAllocAttribute() : this(global::Edict.NoAlloc.Constraints.NoAlloc) { }

                public NoAllocAttribute(global::Edict.NoAlloc.Constraints constraints) => Constraints = constraints | global::Edict.NoAlloc.Constraints.NoAlloc;

                public global::Edict.NoAlloc.Constraints Constraints { get; }

                public global::Edict.NoAlloc.Allow Allow { get; set; }

                public string? Reason { get; set; }
            }

            [global::Microsoft.CodeAnalysis.Embedded]
            [global::System.AttributeUsage(
                global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct
                | global::System.AttributeTargets.Method | global::System.AttributeTargets.Constructor | global::System.AttributeTargets.Property,
                Inherited = false, AllowMultiple = false)]
            internal sealed class NoAllocUncheckedAttribute : global::System.Attribute
            {
                public NoAllocUncheckedAttribute(string reason) => Reason = reason;

                public string Reason { get; }
            }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output => output.AddEmbeddedAttributeDefinition());

        var inject = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            !(options.GlobalOptions.TryGetValue(OptionName, out var value)
              && value.Trim().Equals("false", StringComparison.OrdinalIgnoreCase)));

        context.RegisterSourceOutput(inject, static (output, enabled) =>
        {
            if (enabled)
                output.AddSource(HintName, Source);
        });
    }
}
